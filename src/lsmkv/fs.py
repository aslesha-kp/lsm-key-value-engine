"""Single database directory, serial storage I/O boundary.

The adapter is bound to a database path whose parent already exists durably.
It may start with the database directory missing. ensure_directory is idempotent;
it creates only that directory. sync_parent persists its entry, independently
of sync_dir (child names) and sync_file (inode bytes). No implicit barriers.

Names are single components. create is exclusive, rename atomically replaces
its destination (same-inode rename is a no-op), unlink requires an existing
name. Reads return up to size bytes; None reads to EOF. Writes accept all bytes
or raise, possibly after partial effects. None offset means append. Truncation
zero-fills extensions. Successful syncs persist prior relevant mutations;
errors may have effects and callers must not assume rollback or retry safety.

close is idempotent, releases owned locks/descriptors, and does not sync.
Other operations on a closed adapter raise ValueError except reopen, which
reopens resources without creating the directory, syncing, or recovering data.
Lock tokens are opaque; exclusivity must be cross-process in a real adapter.
The implementation owns any descriptors required for these path-based calls.
sync_primitive identifies the actual durability primitive used.
"""
from typing import Protocol


class FileSystem(Protocol):
    sync_primitive: str

    def directory_exists(self) -> bool: ...
    def ensure_directory(self) -> None: ...
    def sync_parent(self) -> None: ...
    def close(self) -> None: ...
    def reopen(self) -> None: ...
    def create(self, name: str) -> None: ...
    def read(self, name: str, offset: int = 0, size: int | None = None) -> bytes: ...
    def write(self, name: str, data: bytes, offset: int | None = None) -> None: ...
    def truncate(self, name: str, size: int) -> None: ...
    def listdir(self) -> list[str]: ...
    def sync_file(self, name: str) -> None: ...
    def sync_dir(self) -> None: ...
    def rename(self, source: str, destination: str) -> None: ...
    def unlink(self, name: str) -> None: ...
    def lock(self, name: str) -> object: ...
    def unlock(self, token: object) -> None: ...
